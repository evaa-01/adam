# Usage: python scripts\apply_n64sym.py [n64sym_output ...]
#        (default: n64sym_game.txt, then n64sym_thorough.txt if present)
# When several files name the same address, the first file's name wins.
# Takes n64sym's library matches and writes the trustworthy ones into splat\symbol_addrs.txt,
# so splat names those functions (osCreateThread, osRecvMesg, ...). Run scripts\rebuild.ps1 after.
# Only applies a match when it lands exactly on a known function start inside the boot section,
# where the libraries live. Matches elsewhere are listed for review, never applied.
import re, sys, os, json

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # project folder (scripts\..)
SRCS = [os.path.join(BASE, f) for f in (sys.argv[1:] or ["n64sym_game.txt", "n64sym_thorough.txt"])]
SRCS = [f for f in SRCS if os.path.exists(f)]
SYM = BASE + r"\symbols.toml"
ADDRS = BASE + r"\splat\symbol_addrs.txt"
NAMES = BASE + r"\scripts\n64recomp_names.json"
BOOT_LO, BOOT_HI = 0x80096400, 0x800CA8B0
BEGIN, END = "// ---- n64sym begin (generated by apply_n64sym.py) ----", "// ---- n64sym end ----"

lists = json.load(open(NAMES))
kind = {}
for k in ("reimplemented", "ignored", "renamed"):
    for n in lists[k]:
        kind.setdefault(n, k)          # a name can be on several lists; first one wins

syms = []
for f in SRCS:
    syms += [(n, int(a, 16)) for n, a in re.findall(r"^(\S+)\s*=\s*0x([0-9A-Fa-f]+);", open(f).read(), re.M)]
funcs = {int(a, 16): n for n, a in re.findall(r'name = "([^"]+)", vram = (0x[0-9A-Fa-f]+), size', open(SYM).read())}

apply, review, used, named_addr = [], [], set(), set()
for n, a in syms:                       # file order kept, so the first file wins
    if a in named_addr:
        continue
    if re.search(r"_(text|data|rodata|bss)_[0-9A-Fa-f]+$", n):
        continue                      # n64sym's placeholder labels, not real names
    if a not in funcs:
        continue                      # not a function start (label inside a function, or data)
    if not (BOOT_LO <= a < BOOT_HI):
        if (n, a) not in review:
            review.append((n, a))         # library name outside the library area: suspicious
        continue
    name = n if n not in used else f"{n}_{a:08X}"   # same static name in two objects
    used.add(name)
    named_addr.add(a)
    apply.append((name, a))
apply.sort(key=lambda x: x[1])

lines = [l.rstrip("\n") for l in open(ADDRS)] if os.path.exists(ADDRS) else []
if BEGIN in lines:
    i, j = lines.index(BEGIN), lines.index(END)
    lines = lines[:i] + lines[j + 1:]
lines += [BEGIN] + [f"{n} = 0x{a:08X}; // type:func" for n, a in apply] + [END]
open(ADDRS, "w").write("\n".join(lines) + "\n")

from collections import Counter
c = Counter(kind.get(n, "recompiled normally") for n, a in apply)
print(f"read: {', '.join(os.path.basename(f) for f in SRCS)}")
print(f"applied {len(apply)} names to splat\\symbol_addrs.txt")
for k in ("reimplemented", "ignored", "renamed", "recompiled normally"):
    print(f"  {k:20} {c.get(k, 0)}")
if review:
    print(f"\nNOT applied (library name outside the boot section, check by hand): {len(review)}")
    for n, a in review:
        print(f"  {n} @ {a:08X}  [{kind.get(n, 'not in N64Recomp lists')}]")
