# Writes runtime\src\bezel_images.inc: the game's named full-screen images that have a palette (the same 93 that
# scripts\export_named_images.py exports in colour), as {image number, "8-char name"} for runtime\src\bezels.cpp.
# Only numbers and names go into the repo; the pictures are decoded from the player's ROM at run time.
# Usage: python scripts\make_bezel_list.py   (needs rom\game.z64)
import os, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import yay0
from export_named_images import table_entries, IMAGE_ROM, IMAGE_TABLE, PAIRS, boot_rom, load_palette

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    rom = open(os.path.join(BASE, "rom", "game.z64"), "rb").read()
    entries = []
    for index, at, packed, size in table_entries(rom, IMAGE_ROM, IMAGE_TABLE):
        data = yay0.decompress(rom, at) if packed else rom[at:at + size]
        if len(data) < 16:
            continue
        width, height = struct.unpack_from(">HH", data, 0)
        name = data[8:16]
        if not (64 <= width <= 640 and 32 <= height <= 480 and width * height + 16 == len(data)
                and all(48 <= c < 123 for c in name)):
            continue
        image_index, palette_index = struct.unpack_from(">HH", rom, boot_rom(PAIRS) + index * 4)
        if image_index != index or load_palette(rom, palette_index) is None:
            continue
        entries.append((index, name.decode(), width, height))
    out = os.path.join(BASE, "runtime", "src", "bezel_images.inc")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by scripts\\make_bezel_list.py - the game's named images with a palette: {image number, name}\n")
        f.write("// (size in the comment). Don't edit.\n")
        for index, name, width, height in entries:
            f.write(f'{{ {index}, "{name}" }}, // {width}x{height}\n')
    print(f"{len(entries)} images written to {out}")


if __name__ == "__main__":
    main()
