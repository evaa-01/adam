# Writes runtime\src\live_natives.inc for the live shell (runtime\src\live.cpp): the library functions the game
# calls that N64Recomp doesn't recompile (its reimplemented/ignored lists), mapped to the runtime's native
# <name>_recomp implementations. Only names: the list is taken from what the static build's generated code calls.
# Usage (after scripts\rebuild.ps1): python scripts\make_live_natives.py
import glob, json, os, re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # project folder (scripts\..)

lists = json.load(open(os.path.join(BASE, "scripts", "n64recomp_names.json")))
replaced = set(lists["reimplemented"]) | set(lists["ignored"])
symbol_names = set(re.findall(r'name = "([^"]+)"', open(os.path.join(BASE, "symbols.toml")).read()))
called = set()
for path in glob.glob(os.path.join(BASE, "RecompiledFuncs", "funcs_*.c")):
    called |= set(re.findall(r"\b(\w+)_recomp\(rdram", open(path).read()))
names = sorted(n for n in replaced & symbol_names if n in called)

out = os.path.join(BASE, "runtime", "src", "live_natives.inc")
with open(out, "w", newline="\n") as f:
    f.write("// Generated by scripts\\make_live_natives.py: library functions the game calls that the runtime provides\n")
    f.write("// natively (N64Recomp's reimplemented/ignored lists). Used by live.cpp to fill the function tables.\n")
    for n in names:
        f.write(f'extern "C" void {n}_recomp(uint8_t* rdram, recomp_context* ctx);\n')
    f.write("\nstatic const std::pair<const char*, recomp_func_t*> live_natives[] = {\n")
    for n in names:
        f.write(f'    {{ "{n}", {n}_recomp }},\n')
    f.write("};\n")
print(f"{len(names)} natives -> {out}")
