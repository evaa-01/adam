# Usage: python scripts\rewind_ranges.py
# Writes runtime\src\rewind_ranges.inc: the RDRAM ranges rewind (runtime\src\rewind.cpp) must NOT roll back, because only
# "system" code uses them: the idle/scheduler/task code, the music and audio library and libultra (boot code
# 0x800AD7B0-0x800CB000). Their state belongs with host-side things that aren't rewound (tasks in flight, audio
# playing, OS threads); e.g. rolling back the graphics-pending flag 0x8016D060 left the game waiting forever for a
# task that had already finished. Variables the game's own code (anything else, incl. all overlays) also uses are
# rewound. From splat's asm (splat\asm\*.s, needs scripts\rebuild.ps1 once): each D_ symbol runs to the next one.
import collections
import os
import re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # project folder (scripts\..)
ASM = os.path.join(BASE, "splat", "asm")
OUT = os.path.join(BASE, "runtime", "src", "rewind_ranges.inc")
SYS_LO, SYS_HI = 0x800AD7B0, 0x800CB000

refs = collections.defaultdict(set)  # address -> {(file, function, function vram)}
for name in sorted(os.listdir(ASM)):
    if not name.endswith(".s"):
        continue
    func, vram, want_vram = None, None, False
    for line in open(os.path.join(ASM, name), encoding="utf-8", errors="replace"):
        m = re.match(r"\s*glabel (\S+)", line)
        if m:
            func, want_vram = m.group(1), True
            continue
        m = re.match(r"\s*/\* [0-9A-F]+ ([0-9A-F]{8}) [0-9A-F]{8} \*/", line)
        if m and want_vram:
            vram, want_vram = int(m.group(1), 16), False
        if func is not None:
            for d in re.findall(r"D_([0-9A-F]{8})", line):
                refs[int(d, 16)].add((name, func, vram))

def is_system(ref):
    name, func, vram = ref
    return name == "1000.s" and vram is not None and SYS_LO <= vram < SYS_HI

addrs = sorted(a for a in refs if 0x80000000 <= a < 0x80800000)
ranges = []  # [lo, hi, functions]
for i, a in enumerate(addrs):
    if not all(is_system(r) for r in refs[a]):
        continue
    hi = addrs[i + 1] if i + 1 < len(addrs) else a + 4
    funcs = {r[1] for r in refs[a]}
    if ranges and ranges[-1][1] == a:
        ranges[-1][1] = hi
        ranges[-1][2] |= funcs
    else:
        ranges.append([a, hi, funcs])

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts\\rewind_ranges.py - RDRAM ranges only system code uses (not rewound). Don't edit.\n")
    for lo, hi, funcs in ranges:
        names = sorted(funcs)
        f.write("{ 0x%08X, 0x%08X }, // %s\n" % (lo, hi, " ".join(names[:3]) + (" ..." if len(names) > 3 else "")))
print("%d ranges, 0x%X bytes -> %s" % (len(ranges), sum(hi - lo for lo, hi, _ in ranges), OUT))
